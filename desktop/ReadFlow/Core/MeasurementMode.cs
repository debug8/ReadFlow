namespace ReadFlow.Core
{
    /// <summary>
    /// Спосіб отримати час читання. Режими A і B — це дві відповіді на одне питання
    /// «скільки тривало читання», тому вони взаємовиключні.
    ///
    /// Режим C (відмітка помилок) сюди не входить навмисно: він не про час, а про
    /// якість, і накладається поверх будь-якого з цих двох — див.
    /// <c>MainViewModel.MarkErrors</c>.
    /// </summary>
    public enum MeasurementMode
    {
        /// <summary>Режим A: час фіксований, учитель клікає на слові, де учень зупинився.</summary>
        ClickStop = 0,

        /// <summary>Режим B: учитель тисне Старт і Стоп, час фактичний.</summary>
        Timer = 1
    }
}
