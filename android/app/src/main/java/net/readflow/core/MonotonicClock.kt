package net.readflow.core

/**
 * Джерело часу для заміру.
 *
 * Час береться **монотонним** годинником, а не накопиченням тіків таймера
 * інтерфейсу (`SPEC.md`, 4.8): тіки затримуються під навантаженням, і за
 * хвилину набігає похибка в кілька секунд — а це прилад вимірювання.
 *
 * Інтерфейс потрібен ще й тестам: у них годинник іде віртуальним часом
 * корутинного планувальника, тож замір «на дві хвилини» перевіряється
 * миттєво й без флейків.
 */
fun interface MonotonicClock {

    /** Скільки мілісекунд минуло від довільної точки в минулому. */
    fun millis(): Long

    companion object {

        /**
         * Системний годинник. `nanoTime` не звʼязаний із годинником стіни,
         * тож переведення часу на телефоні посеред заміру його не зіпсує.
         */
        val Default = MonotonicClock { System.nanoTime() / 1_000_000 }
    }
}
