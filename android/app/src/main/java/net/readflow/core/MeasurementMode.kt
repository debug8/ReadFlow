package net.readflow.core

/**
 * Режим заміру — те, що вчитель обирає сегментованим перемикачем угорі
 * (`SPEC_ANDROID.md`, 2.1: «три великі кнопки»).
 *
 * Усередині це дві незалежні осі зі `SPEC.md`, 4.7–4.8, а не три несумісні
 * стани:
 *
 * | Режим | Звідки час | Короткий тап | Довгий тап |
 * |-------|------------|--------------|------------|
 * | A     | обрана тривалість | межа читання | номер слова |
 * | B     | секундомір | межа читання | номер слова |
 * | C     | секундомір | помилка | межа читання + номер слова |
 *
 * Саме тому «режими поєднуються», як вимагає Задача 6: межа з A нікуди не
 * зникає в C — вона лише переїжджає на довгий тап, — а час у C береться з
 * того самого секундоміра, що й у B.
 *
 * На десктопі ці осі розведені по двох контролах (`MeasurementMode` +
 * прапорець «Відмічати помилки»), бо там є і правий клік, і місце в панелі.
 * Числа від цього не залежать: обидві платформи рахують за тими самими
 * правилами розділу 4.
 */
enum class MeasurementMode {

    /** A «Тап = стоп»: час фіксований, учитель тапає слово, де учень зупинився. */
    TAP_STOP,

    /** B «Таймер + стоп»: час фактичний, зі секундоміра. */
    TIMER,

    /** C «Помилки»: час фактичний, тап позначає помилку. */
    ERRORS;

    /** Чи береться час із обраної тривалості, а не з секундоміра (`SPEC.md`, 4.8). */
    val usesFixedDuration: Boolean get() = this == TAP_STOP

    /** Чи позначає короткий тап помилку замість межі читання (`SPEC.md`, 4.7). */
    val marksErrors: Boolean get() = this == ERRORS
}
