package net.readflow.model

/**
 * Як позначене окреме слово в режимі читання.
 *
 * Один перелік на всі три режими заміру: межу ставить режим A, помилку — режим C
 * (`SPEC.md`, 4.7). У Задачі 4 позначок ще немає — усі слова [NONE], — але стиль
 * малюється по цьому переліку вже зараз, щоб наступні задачі додавали лише
 * джерело позначок, а не переписували рендер.
 */
enum class WordMark {

    /** Звичайне слово: власного стилю не має, успадковує стиль усього тексту. */
    NONE,

    /** Межа читання — докуди учень дочитав (режим A). */
    BOUNDARY,

    /** Помилка при читанні (режим C). */
    ERROR
}
