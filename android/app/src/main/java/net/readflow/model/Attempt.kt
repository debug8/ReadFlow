package net.readflow.model

/**
 * Один запис історії — збережений підсумок заміру (`SPEC_ANDROID.md`, 2.1,
 * «Історія»; Задача 8).
 *
 * Це доменна модель, незалежна від Room: сховище повертає саме її, а не
 * `@Entity`, щоб ViewModel і CSV-експортер лишалися без залежностей від
 * Android і перевірялися звичайними JVM-тестами.
 *
 * Набір полів — рівно той, що просить Задача 8: імʼя учня, дата-час, WPM,
 * знаків/хв, помилки, % помилок і клас. Час читання й режим у запис не йдуть:
 * історія — це журнал результатів, а не повний протокол заміру.
 */
data class Attempt(

    /** Ключ у сховищі. `0` — запис ще не збережений. */
    val id: Long = 0L,

    /** Імʼя учня або порожній рядок, якщо вчитель його не ввів. */
    val studentName: String = "",

    /** Момент заміру — epoch-мілісекунди UTC. Формат дати — справа інтерфейсу. */
    val createdAt: Long = 0L,

    /** Клас учня (1–4) або 0, якщо не обрано. */
    val grade: Int = 0,

    /** Слів за хвилину. */
    val wordsPerMinute: Int = 0,

    /** Знаків за хвилину. */
    val charsPerMinute: Int = 0,

    /** Кількість помилок у межах прочитаного. */
    val errors: Int = 0,

    /** Відсоток помилок від прочитаного, до 0.1. */
    val errorPercent: Double = 0.0
)
