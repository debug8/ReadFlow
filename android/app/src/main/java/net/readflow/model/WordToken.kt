package net.readflow.model

/**
 * Одне слово тексту разом із його межами. Межі потрібні, щоб у режимі читання
 * відрендерити кожне слово окремим діапазоном і показати «Слово №N» (Задача 4),
 * а також щоб тап по слову визначав межу читання (Задача 6).
 */
data class WordToken(

    /** Порядковий номер слова в тексті, від 1. */
    val number: Int,

    /** Саме слово, як воно записане в тексті (разом з апострофами й дефісами). */
    val text: String,

    /** Індекс першого символу слова у вихідному тексті. */
    val start: Int,

    /** Кількість букв у слові — без апострофів і дефісів (див. `SPEC.md`, 4.1). */
    val letterCount: Int
) {
    /** Довжина слова в символах. */
    val length: Int get() = text.length

    /** Індекс символу одразу після слова (напівінтервал `[start, end)`). */
    val end: Int get() = start + text.length
}
